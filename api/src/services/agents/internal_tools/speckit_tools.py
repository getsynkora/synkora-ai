"""
Spec-Kit SDD Tools for Synkora Agents.

Persistence-only tools that upload agent-generated spec artifacts to S3
and optionally commit them to GitHub. The agent (LLM) generates all markdown
content; these tools handle storage and identity.
"""

import base64
import logging
from typing import Any

import httpx

from src.services.agents.internal_tools.github_auth_helper import get_github_token_from_context
from src.services.storage.s3_storage import get_s3_storage

logger = logging.getLogger(__name__)

_S3_EXPIRY = 86400 * 7  # 7 days


def _get_tenant_id(config: dict[str, Any] | None) -> str:
    """Extract tenant_id string from runtime context, falling back to 'unknown'."""
    if config:
        rc = config.get("_runtime_context")
        if rc and getattr(rc, "tenant_id", None):
            return str(rc.tenant_id)
    return "unknown"


def _s3_key(tenant_id: str, feature_id: str, filename: str) -> str:
    return f"speckit/{tenant_id}/{feature_id}/{filename}"


async def _upload_markdown(tenant_id: str, feature_id: str, filename: str, content: str) -> dict[str, Any]:
    """Upload markdown string to S3, return s3_key and presigned URL. Raises on failure."""
    s3 = get_s3_storage()
    key = _s3_key(tenant_id, feature_id, filename)
    s3.upload_file(
        file_content=content.encode("utf-8"),
        key=key,
        content_type="text/markdown",
    )
    url = s3.generate_presigned_url(key=key, expiration=_S3_EXPIRY)
    return {"s3_key": key, "s3_url": url}


async def internal_speckit_specify(
    feature_id: str,
    spec_content: str,
    repo_url: str | None = None,
    config: dict[str, Any] | None = None,
    runtime_context: Any = None,
) -> dict[str, Any]:
    """
    Save an agent-generated spec to S3 and return a presigned download URL.

    The agent must generate spec_content before calling this tool.
    spec_content must include these sections:
      Overview | Problem Statement | User Stories | Functional Requirements |
      Non-Functional Requirements | Out of Scope | Open Questions
      (use [NEEDS CLARIFICATION] for unresolved items)

    Args:
        feature_id: Feature identifier in FEAT-NNNN format (e.g. "FEAT-0001")
        spec_content: Full spec markdown generated by the agent
        repo_url: Optional repository URL stored as metadata
        config: Tool config dict containing _runtime_context
        runtime_context: Unused (context comes via config)

    Returns:
        {"filename", "feature_id", "s3_url", "s3_key"} on success
        {"filename", "feature_id", "content", "storage_error": True} if S3 fails
        {"error": str} if input validation fails
    """
    if not spec_content or not spec_content.strip():
        return {"error": "spec_content is required and must not be empty"}
    if not feature_id or not feature_id.strip():
        return {"error": "feature_id is required"}

    tenant_id = _get_tenant_id(config)
    filename = "spec.md"

    try:
        upload = await _upload_markdown(tenant_id, feature_id, filename, spec_content)
        return {
            "filename": filename,
            "feature_id": feature_id,
            "s3_url": upload["s3_url"],
            "s3_key": upload["s3_key"],
        }
    except Exception as e:
        logger.error(f"speckit_specify S3 upload failed: {e}", exc_info=True)
        return {
            "filename": filename,
            "feature_id": feature_id,
            "content": spec_content,
            "storage_error": True,
            "storage_error_message": str(e),
        }


